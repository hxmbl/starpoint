// Package oslog generates the operating system's own log-retention
// configuration for Starpoint's logs.
//
// Starpoint's retention already works everywhere: it deletes its own audit
// files once they pass the window, on every command, with no privileges. What
// it cannot do by itself is the part the system's logger is good at — compressing
// what is still inside the window and capping how many rotated copies survive —
// and that is what the configuration generated here asks the system logger to
// take on.
//
// The support split follows what each platform actually offers:
//
//   - Linux has logrotate, whose whole job is this and whose configuration is a
//     plain user-editable text file. This is the easy case.
//   - macOS has newsyslog, which needs the same information in a more rigid
//     grammar and has no per-user configuration: newsyslog runs as root from
//     /etc. That is the harder case, and it is why the generated file is written
//     to Starpoint's own directory rather than installed.
//   - Windows has its own event log with its own retention settings, and is not
//     addressed here.
//
// Nothing in this package writes to a system directory. It returns the text and
// a note; Starpoint writes the file under its own state directory and tells the
// user the one command that installs it where the system logger reads it.
// Writing into /etc is a privilege escalation done on somebody's behalf, and a
// tool that manages other people's software has no business taking it.
package oslog

import (
	"fmt"
	"path/filepath"
	"runtime"
	"strings"
)

// Mechanism names the system logger a configuration is written for.
type Mechanism string

const (
	// Logrotate is Linux's logrotate.
	Logrotate Mechanism = "logrotate"
	// Newsyslog is macOS's newsyslog.
	Newsyslog Mechanism = "newsyslog"
	// Unsupported means this platform has no configuration generated.
	Unsupported Mechanism = "unsupported"
)

// Config is a generated retention configuration.
type Config struct {
	// Goos is the platform it was generated for.
	Goos string `json:"goos"`
	// Supported reports whether this platform has a mechanism at all.
	Supported bool `json:"supported"`
	// Mechanism is the system logger the configuration is for.
	Mechanism Mechanism `json:"mechanism"`
	// Path is where Starpoint writes the generated file.
	Path string `json:"path,omitempty"`
	// SystemPath is where the system logger expects such a file. Starpoint does
	// not write there.
	SystemPath string `json:"system_path,omitempty"`
	// Content is the generated configuration.
	Content string `json:"content,omitempty"`
	// Note explains the state of things in a sentence fit for a terminal.
	Note string `json:"note,omitempty"`
}

// Generate produces the retention configuration for a platform.
//
// goos is taken as an argument rather than read from the runtime so that the
// generation is testable for a platform the test is not running on.
func Generate(goos, logDir string, days int) Config {
	if days <= 0 {
		days = 30
	}
	switch goos {
	case "linux":
		return Config{
			Goos:       goos,
			Supported:  true,
			Mechanism:  Logrotate,
			Path:       filepath.Join(configDirFor(logDir), "starpoint.logrotate"),
			SystemPath: "/etc/logrotate.d/starpoint",
			Content:    logrotateConfig(logDir, days),
			Note: fmt.Sprintf("logrotate reads %s. Copy the generated file there to have the system logger compress and cap Starpoint's logs as well.",
				"/etc/logrotate.d/starpoint"),
		}
	case "darwin":
		return Config{
			Goos:       goos,
			Supported:  true,
			Mechanism:  Newsyslog,
			Path:       filepath.Join(configDirFor(logDir), "starpoint.newsyslog"),
			SystemPath: "/etc/newsyslog.d/starpoint.conf",
			Content:    newsyslogConfig(logDir, days),
			Note: "macOS has no per-user log rotation: newsyslog runs as root from /etc. " +
				"Copy the generated file to /etc/newsyslog.d/ to hand these logs to the system logger. " +
				"Starpoint's own retention already deletes expired files without it.",
		}
	default:
		return Config{
			Goos:      goos,
			Supported: false,
			Mechanism: Unsupported,
			Note: "No system log retention configuration is generated for " + goos +
				". Starpoint still deletes its own expired records; Windows' event log keeps its own retention settings.",
		}
	}
}

// GenerateForHost generates the configuration for the running platform.
func GenerateForHost(logDir string, days int) Config {
	return Generate(runtime.GOOS, logDir, days)
}

// configDirFor places generated configuration beside the logs it governs.
func configDirFor(logDir string) string {
	return filepath.Join(filepath.Dir(logDir), "logging")
}

func logrotateConfig(logDir string, days int) string {
	return fmt.Sprintf(`# Starpoint's audit log, generated by 'str logging config'.
#
# Starpoint already deletes audit files older than %[1]d days itself, on every
# command and without privileges. What logrotate adds is the part Starpoint does
# not do: compressing what is still inside the window, and capping how many
# rotated copies survive on disk.
#
# To install:  sudo cp %[2]s /etc/logrotate.d/starpoint
%[3]s/audit-*.jsonl {
    daily
    rotate %[1]d
    maxage %[1]d
    missingok
    notifempty
    compress
    delaycompress
    copytruncate
}
`, days, filepath.Join(configDirFor(logDir), "starpoint.logrotate"), logDir)
}

func newsyslogConfig(logDir string, days int) string {
	// The newsyslog line is: path [owner:group] mode rotate time flags.
	// "J" means rotate and compress; that is the behaviour wanted here.
	return fmt.Sprintf(`# Starpoint's audit log, generated by 'str logging config'.
#
# The line below is: path, mode, rotate count, rotation age, then flags.
# "J" means newsyslog rotates and compresses the file.
#
# macOS has no per-user log rotation, so this only takes effect once the file is
# installed for the system:
#   sudo cp %s /etc/newsyslog.d/starpoint.conf
#
# Starpoint deletes expired audit files itself either way.
%s/audit-*.jsonl 644 %d %dd * J
`, filepath.Join(configDirFor(logDir), "starpoint.newsyslog"), logDir, days, days)
}

// InstallHint is the command that puts a generated file where the system logger
// reads it.
func InstallHint(c Config) string {
	if !c.Supported || c.SystemPath == "" {
		return ""
	}
	return "sudo cp " + c.Path + " " + c.SystemPath
}

// LooksGenerated reports whether a file's contents look like something this
// package wrote, so Starpoint never overwrites something it does not own.
// Files written before the executable was renamed to str carry the old
// command in their marker and are still Starpoint's.
func LooksGenerated(content string) bool {
	return strings.Contains(content, "generated by 'str logging config'") ||
		strings.Contains(content, "generated by 'starpoint logging config'")
}
